def _loss_sweep(summary: pd.DataFrame) -> pd.DataFrame:
    sweep = summary[summary["experiment"].isin(LOSS_EXPERIMENTS)].copy()
    sweep["loss_percent"] = sweep["loss_rate"] * 100.0
    return sweep.sort_values("loss_percent")


def plot_metric_vs_loss(summary: pd.DataFrame, metric: str, *, title: str,
                        subtitle: str = "", plot_dir: Path = PLOT_DIR,
                        name: str | None = None,
                        systems: tuple[str, ...] = SYSTEM_ORDER) -> Path:
    """One §27 graph: a metric against the loss grid, one line per system.

    Error bars are the standard deviation across the cell's trials (D12 = 5), not
    a confidence interval: with five runs the spread is worth showing and an
    interval would imply more than five runs support.
    """
    sweep = _loss_sweep(summary)
    figure, axes = _figure()
    labels = []
    for system in systems:
        series = sweep[sweep["system"] == system]
        if series.empty:
            continue
        x = series["loss_percent"].to_numpy()
        y = series[f"{metric}_mean"].to_numpy()
        axes.errorbar(x, y, yerr=series[f"{metric}_sd"].to_numpy(),
                      color=SERIES_COLOR[system], marker=SERIES_MARKER[system],
                      markersize=6, linewidth=1.8, capsize=3, elinewidth=1.0,
                      dashes=SERIES_DASH[system], label=SYSTEM_LABEL[system],
                      markeredgecolor=SURFACE, markeredgewidth=0.8)
        labels.append((SYSTEM_LABEL[system], x[-1], y[-1]))

    _finish(axes, title=title, subtitle=subtitle,
            xlabel="Packet-loss rate (%)", ylabel=METRICS[metric])
    axes.set_xticks(sorted(sweep["loss_percent"].unique()))
    axes.set_xlim(-1.2, sweep["loss_percent"].max() * 1.16)
    axes.set_ylim(bottom=0)
    _direct_labels(axes, labels)
    _legend(axes, len(labels))
    return _save(figure, name or f"{metric}_vs_loss.png", plot_dir)


def plot_mode_timeline(frame: pd.DataFrame, *, plot_dir: Path = PLOT_DIR,
                       log_root: Path | None = None) -> Path:
    """Mode selection over time under dynamic loss (specs.md §27, E8).

    Read straight from each run's ``events.csv``: every row carries the mode that
    was live when it was written, so the timeline is the log's own account of
    what the controller did, not a reconstruction. Scheduled loss changes are
    drawn from the ``LOSS_CHANGE`` rows the simulator emitted, so the picture
    shows what the run actually met rather than what its config asked for.
    """
    runs = frame[(frame["experiment"] == DYNAMIC_EXPERIMENT) & frame["ok"]]
    conditions = list(dict.fromkeys(runs["condition"]))
    figure, all_axes = plt.subplots(
        len(conditions), 1, figsize=(7.8, 1.45 * len(conditions) + 1.9), dpi=150,
        sharex=True)
    figure.patch.set_facecolor(SURFACE)
    all_axes = all_axes if len(conditions) > 1 else [all_axes]

    for axes, condition in zip(all_axes, conditions):
        axes.set_facecolor(SURFACE)
        cell = runs[runs["condition"] == condition].sort_values("trial")
        for row_index, run in enumerate(cell.to_dict("records")):
            directory = runner._resolve(run["log_dir"])
            if log_root is not None:
                directory = Path(log_root) / directory.name
            spans, changes = _mode_spans(directory / "sender" / "events.csv")
            for start, end, mode in spans:
                axes.broken_barh(
                    [(start, max(end - start, 0.02))], (row_index + 0.6, 0.78),
                    facecolors=MODE_COLOR.get(mode, INK_MUTED),
                    edgecolors=SURFACE, linewidth=1.0)   # 2px surface gap
            if row_index == 0:
                for moment, _ in changes:
                    axes.axvline(moment, color=INK_SECONDARY, linewidth=1.0,
                                 linestyle=(0, (2, 2)), zorder=3)
        axes.set_yticks([index + 1 for index in range(len(cell))])
        axes.set_yticklabels([f"trial {trial}" for trial in cell["trial"]],
                             fontsize=8, color=INK_SECONDARY)
        # Trial 0 at the top: the rows read in the order they were run.
        axes.set_ylim(len(cell) + 0.6, 0.4)
        axes.text(0.0, 1.06, condition, transform=axes.transAxes, ha="left",
                  va="bottom", color=INK, fontsize=10, fontweight="semibold")
        for side in ("top", "right", "left"):
            axes.spines[side].set_visible(False)
        axes.spines["bottom"].set_color(GRID)
        axes.tick_params(colors=INK_SECONDARY, labelsize=9, length=3)
        axes.grid(axis="x", color=GRID, linewidth=0.8)
        axes.set_axisbelow(True)

    all_axes[-1].set_xlabel("Time since the sender started (s)",
                            color=INK_SECONDARY, fontsize=10)
    # Title and subtitle on the figure, not on the first subplot: each subplot
    # already carries a condition heading, and a third layer of text on that one
    # set of axes collides with it.
    figure.suptitle("Mode selection over time under dynamic loss", color=INK,
                    fontsize=12, fontweight="semibold", x=0.125, y=1.035,
                    ha="left")
    figure.text(0.125, 0.995,
                "E8 · hybrid · 5 trials per condition · dashed line = a "
                "scheduled loss change",
                ha="left", va="bottom", color=INK_SECONDARY, fontsize=9)

    handles = [plt.Line2D([], [], color=MODE_COLOR[mode], linewidth=8,
                          label=SYSTEM_LABEL[mode]) for mode in ("gbn", "sr")]
    legend = figure.legend(handles=handles, frameon=False, fontsize=9, ncol=2,
                           loc="lower left", bbox_to_anchor=(0.125, -0.02))
    for text in legend.get_texts():
        text.set_color(INK_SECONDARY)
    return _save(figure, "mode_selection_over_time.png", plot_dir)


def _mode_spans(events_path: Path) -> tuple[list[tuple[float, float, str]],
                                            list[tuple[float, str]]]:
    """Contiguous runs of one mode, and the loss changes, from one event log."""
    spans: list[tuple[float, float, str]] = []
    changes: list[tuple[float, str]] = []
    start, current, last = None, None, 0.0
    with open(events_path, newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            moment = float(row["timestamp"])
            last = moment
            if row["event"] == "LOSS_CHANGE":
                changes.append((moment, row["reason"]))
            mode = row["mode"]
            if not mode:
                continue
            if current is None:
                start, current = moment, mode
            elif mode != current:
                spans.append((start, moment, current))
                start, current = moment, mode
    if current is not None:
        spans.append((start, last, current))
    return spans, changes


