def _figure(width: float = 7.6, height: float = 4.6):
    figure, axes = plt.subplots(figsize=(width, height), dpi=150)
    figure.patch.set_facecolor(SURFACE)
    axes.set_facecolor(SURFACE)
    return figure, axes


def _wrap(subtitle: str, width: int = 86) -> str:
    """Keep a subtitle inside the plot, rather than letting it widen the figure.

    ``bbox_inches="tight"`` grows the canvas around an overlong line, which
    quietly changes the aspect ratio of one figure in a set that is meant to be
    read side by side.
    """
    return "\n".join(textwrap.wrap(subtitle, width=width)) if subtitle else ""


def _finish(axes, *, title: str, xlabel: str, ylabel: str, subtitle: str = "") -> None:
    """Recessive grid and axes, ink-coloured text, no chartjunk."""
    subtitle = _wrap(subtitle)
    lines = subtitle.count("\n") + 1 if subtitle else 0
    axes.set_title(title, color=INK, fontsize=12, fontweight="semibold",
                   loc="left", pad=10 + 13 * lines)
    if subtitle:
        axes.text(0.0, 1.02, subtitle, transform=axes.transAxes, ha="left",
                  va="bottom", color=INK_SECONDARY, fontsize=9, linespacing=1.4)
    axes.set_xlabel(xlabel, color=INK_SECONDARY, fontsize=10)
    axes.set_ylabel(ylabel, color=INK_SECONDARY, fontsize=10)
    axes.grid(axis="y", color=GRID, linewidth=0.8)
    axes.set_axisbelow(True)
    for side in ("top", "right"):
        axes.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        axes.spines[side].set_color(GRID)
    axes.tick_params(colors=INK_SECONDARY, labelsize=9, length=3)


def _direct_labels(axes, placed: list[tuple[str, float, float]]) -> None:
    """Label each series at its right-hand end, nudged apart when they collide.

    Required rather than decorative: two of the four hues sit below 3:1 contrast
    on this surface, so the palette's relief rule asks for visible labels. Text
    wears ink, never the series colour — the line beside it carries identity.
    """
    span = axes.get_ylim()[1] - axes.get_ylim()[0]
    minimum_gap = span * 0.055
    ordered = sorted(placed, key=lambda item: item[2])
    positions: list[float] = []
    for _, _, y in ordered:
        if positions and y - positions[-1] < minimum_gap:
            y = positions[-1] + minimum_gap
        positions.append(y)
    for (label, x, true_y), y in zip(ordered, positions):
        # A displaced label gets a leader back to the point it names, so a
        # collision never moves a label somewhere it could be misread.
        if abs(y - true_y) > span * 0.005:
            axes.annotate("", xy=(x, true_y), xytext=(x, y),
                          arrowprops=dict(arrowstyle="-", color=INK_MUTED,
                                          linewidth=0.7, shrinkA=1, shrinkB=1))
        axes.annotate(label, xy=(x, y), xytext=(6, 0), textcoords="offset points",
                      color=INK, fontsize=9, va="center", ha="left",
                      fontweight="medium")


def _legend(axes, series_count: int) -> None:
    """A legend for two or more series. One series needs none: the title names
    it and the direct label repeats it, so a legend box would be furniture."""
    if series_count < 2:
        return
    legend = axes.legend(frameon=False, fontsize=9, loc="upper left",
                         bbox_to_anchor=(0.0, -0.16), ncol=4,
                         handlelength=2.4, columnspacing=1.6)
    for text in legend.get_texts():
        text.set_color(INK_SECONDARY)


def _save(figure, name: str, plot_dir: Path) -> Path:
    plot_dir.mkdir(parents=True, exist_ok=True)
    path = plot_dir / name
    figure.savefig(path, bbox_inches="tight", facecolor=SURFACE)
    plt.close(figure)
    return path


