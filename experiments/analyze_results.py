"""Result aggregation, metrics and graphs (T9.1, T9.2, T9.3).

Reads what Phase 8 recorded and writes what specs.md §27 asks for. It **never
re-runs a transfer and never writes to a log**: the inputs are
``experiments/results/experiment_runs.csv`` and the raw ``events.csv`` files
under ``logs/experiments/``, both opened read-only (RP-07).

WHERE THE NUMBERS COME FROM
===========================
The run index is itself derived from the event logs — ``run_experiment.py`` built
every row of it by calling ``metrics.py`` on that run's ``events.csv`` (CC-06).
Aggregating from the index is therefore aggregating from the logs, one step
removed, and it is the step that makes a 195-run sweep tractable.

Because "one step removed" is exactly the kind of claim that quietly stops being
true, ``--check-logs`` re-derives every metric from the raw event rows again and
compares it against the index. It is not a formality: if a log were edited, or
the index regenerated by hand, or `metrics.py` changed after the runs were made,
that check is what fails. `run_experiment.py --verify` answers the neighbouring
question — are the raw logs byte-identical to what the runs wrote (RP-07).

The one thing read straight from the logs in normal use is the mode timeline of
§27's last graph: "mode selection over time" is a *sequence*, and an aggregate
row cannot hold one.

INTEGRITY FAILURES ARE REPORTED, NEVER AVERAGED (CC-01, T9.1)
=============================================================
A run whose hashes did not match has no meaningful goodput — it did not deliver
the file. Such runs are excluded from every aggregate and counted in a column of
their own, so a cell that failed half its trials cannot look like a cell that
merely ran slowly. In the recorded matrix that column is zero everywhere; the
handling exists because a future run may not be so lucky, and because a silently
dropped failure is indistinguishable from a failure that never happened.

CHART CONVENTIONS
=================
Four systems, four fixed categorical hues assigned in a fixed order and never
cycled: GBN blue, SR orange, Hybrid aqua, fixed-hybrid yellow. The palette was
validated for colour-vision deficiency before use (worst adjacent ΔE 9.1 protan,
22.9 normal); two of the four sit below 3:1 contrast on the chart surface, so
every series also carries a distinct marker and dash pattern and is labelled
directly at its right-hand end as well as in the legend. Identity is never
carried by colour alone.

USAGE
=====
    python experiments/analyze_results.py                 # aggregate + all graphs
    python experiments/analyze_results.py --no-plots      # aggregate only
    python experiments/analyze_results.py --check-logs    # re-derive from events.csv
"""

