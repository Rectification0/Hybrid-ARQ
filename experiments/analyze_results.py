def write_aggregate(summary: pd.DataFrame, path: Path = AGGREGATE_CSV) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    summary.to_csv(path, index=False)
    return path


def make_all_plots(frame: pd.DataFrame, summary: pd.DataFrame, *,
                   plot_dir: Path = PLOT_DIR,
                   log_root: Path | None = None) -> list[Path]:
    """Every graph of specs.md §27, required then optional."""
    conditions = "E1-E6 · 1 MiB · 100 ms RTT · window 8 · mean of 5 trials, ±1 sd"
    paths = [
        plot_metric_vs_loss(summary, "goodput_kib_per_s", plot_dir=plot_dir,
                            title="Goodput vs packet-loss rate", subtitle=conditions,
                            name="goodput_vs_loss.png"),
        plot_metric_vs_loss(summary, "retransmission_count", plot_dir=plot_dir,
                            title="Retransmission count vs packet-loss rate",
                            subtitle=conditions, name="retransmissions_vs_loss.png"),
        plot_metric_vs_loss(summary, "retransmission_overhead", plot_dir=plot_dir,
                            title="Retransmission overhead vs packet-loss rate",
                            subtitle="retransmitted / transmitted bytes · " + conditions,
                            name="retransmission_overhead_vs_loss.png"),
        plot_metric_vs_loss(summary, "completion_time_s", plot_dir=plot_dir,
                            title="Completion time vs packet-loss rate",
                            subtitle=conditions, name="completion_time_vs_loss.png"),
        plot_mode_timeline(frame, plot_dir=plot_dir, log_root=log_root),
        # Optional (T9.3)
        plot_goodput_vs_rtt(summary, plot_dir=plot_dir),
        plot_metric_vs_loss(summary, "switch_count", plot_dir=plot_dir,
                            title="Switching frequency vs packet-loss rate",
                            subtitle="a static condition justifies one switch · " + conditions,
                            name="switching_frequency_vs_loss.png",
                            systems=("hybrid",)),
        plot_metric_vs_loss(summary, "sr_residence_fraction", plot_dir=plot_dir,
                            title="Time spent in SR vs packet-loss rate",
                            subtitle="fraction of the transfer · " + conditions,
                            name="sr_residence_vs_loss.png",
                            systems=("hybrid",)),
    ]
    return paths


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Aggregate the recorded runs and draw the specs.md §27 graphs.")
    parser.add_argument("--runs", type=Path, default=RUNS_CSV,
                        help="the run index written by run_experiment.py")
    parser.add_argument("--aggregate", type=Path, default=AGGREGATE_CSV,
                        help="where to write the per-condition aggregate")
    parser.add_argument("--plot-dir", type=Path, default=PLOT_DIR)
    parser.add_argument("--no-plots", action="store_true",
                        help="aggregate only, draw nothing")
    parser.add_argument("--check-logs", action="store_true",
                        help="re-derive every metric from events.csv and compare")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    frame = load_runs(args.runs)
    summary = aggregate(frame)
    path = write_aggregate(summary, args.aggregate)

    failures = integrity_report(frame)
    # ASCII only on stdout: a Windows console is cp1252 and would raise on an
    # arrow or a plus-minus. The figures themselves are UTF-8 and use both.
    print(f"{len(frame)} runs, {int(frame['ok'].sum())} with matching hashes, "
          f"{len(summary)} cells -> {path}")
    if len(failures):
        print(f"{len(failures)} run(s) excluded from every aggregate "
              f"(CC-01: an integrity failure is reported, never averaged):")
        for row in failures.to_dict("records"):
            print(f"  {row['status']:<9} {row['run_id']}: {row['error']}")
    else:
        print("no integrity failures: every recorded run is in the aggregates")

    if args.check_logs:
        mismatches = check_against_logs(frame)
        if mismatches:
            print(f"{len(mismatches)} metric(s) disagree with the raw logs:")
            for row in mismatches[:20]:
                print(f"  {row['run_id']} {row['metric']}: index {row['index']} "
                      f"vs logs {row['from_logs']}")
            return 1
        print(f"all {len(frame)} runs re-derive from events.csv to the same "
              f"numbers the index records (CC-06)")

    if not args.no_plots:
        for plot in make_all_plots(frame, summary, plot_dir=args.plot_dir):
            print(f"  wrote {plot}")
    return 0


