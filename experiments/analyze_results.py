def plot_goodput_vs_rtt(summary: pd.DataFrame, *, plot_dir: Path = PLOT_DIR) -> Path:
    """Goodput against RTT at fixed loss (E7) — the RTT-invariance check."""
    sweep = summary[summary["experiment"] == RTT_EXPERIMENT].sort_values("rtt_ms")
    figure, axes = _figure()
    labels = []
    for system in SYSTEM_ORDER:
        series = sweep[sweep["system"] == system]
        if series.empty:
            continue
        x = series["rtt_ms"].to_numpy()
        y = series["goodput_kib_per_s_mean"].to_numpy()
        axes.errorbar(x, y, yerr=series["goodput_kib_per_s_sd"].to_numpy(),
                      color=SERIES_COLOR[system], marker=SERIES_MARKER[system],
                      markersize=6, linewidth=1.8, capsize=3, elinewidth=1.0,
                      dashes=SERIES_DASH[system], label=SYSTEM_LABEL[system],
                      markeredgecolor=SURFACE, markeredgewidth=0.8)
        labels.append((SYSTEM_LABEL[system], x[-1], y[-1]))
    _finish(axes, title="Goodput vs round-trip time, at 5% loss",
            subtitle="E7 · 1 MiB · window 8 · RTO per condition (D7) · "
                     "mean of 5 trials, ±1 sd",
            xlabel="Round-trip time (ms)", ylabel=METRICS["goodput_kib_per_s"])
    axes.set_xscale("log")
    axes.set_xticks(sorted(sweep["rtt_ms"].unique()))
    axes.get_xaxis().set_major_formatter(matplotlib.ticker.ScalarFormatter())
    axes.set_ylim(bottom=0)
    _direct_labels(axes, labels)
    _legend(axes, len(labels))
    return _save(figure, "goodput_vs_rtt.png", plot_dir)


