def load_runs(path: Path | str = RUNS_CSV) -> pd.DataFrame:
    """Every recorded run, with the derived columns the graphs need.

    Opened read-only. Two columns are added rather than recomputed downstream:
    goodput in KiB/s, because bytes per second plots as an unreadable number,
    and SR residence as a *fraction* of the transfer, because seconds in SR is
    not comparable between a 16 s run and a 140 s one.
    """
    frame = pd.read_csv(path)
    frame["ok"] = frame["status"] == runner.STATUS_OK
    frame["goodput_kib_per_s"] = frame["goodput_bytes_per_s"] / 1024.0
    residence = frame["gbn_residence_s"] + frame["sr_residence_s"]
    frame["sr_residence_fraction"] = (frame["sr_residence_s"] / residence).where(
        residence > 0, 0.0)
    frame["loss_percent"] = frame["loss_rate"] * 100.0
    return frame


def aggregate(frame: pd.DataFrame) -> pd.DataFrame:
    """Mean and spread per (experiment, condition, system), across trials.

    Aggregating over trials rather than reporting one run is the whole point of
    D12's repetition count: a single transfer at 20% loss says very little.

    **Runs whose integrity check failed are excluded from every mean** and
    counted in ``integrity_failures`` instead (CC-01). A corrupted transfer has
    no meaningful goodput, and averaging one into a cell would make the cell
    quietly wrong rather than visibly incomplete.
    """
    rows = []
    keys = ["experiment", "condition", "system"]
    for (experiment, condition, system), cell in frame.groupby(keys, sort=False):
        good = cell[cell["ok"]]
        row = {
            "experiment": experiment,
            "condition": condition,
            "system": system,
            "loss_rate": cell["loss_rate"].iloc[0],
            "rtt_ms": cell["rtt_ms"].iloc[0],
            "loss_schedule": cell["loss_schedule"].iloc[0]
                             if isinstance(cell["loss_schedule"].iloc[0], str) else "",
            "trials": len(cell),
            "trials_aggregated": len(good),
            "integrity_failures": int((~cell["ok"]).sum()),
        }
        for metric in METRICS:
            values = good[metric]
            row[f"{metric}_mean"] = values.mean() if len(values) else float("nan")
            row[f"{metric}_sd"] = values.std(ddof=1) if len(values) > 1 else 0.0
        rows.append(row)
    return pd.DataFrame(rows)


def integrity_report(frame: pd.DataFrame) -> pd.DataFrame:
    """The runs kept out of the aggregates, listed rather than summarised."""
    failed = frame[~frame["ok"]]
    return failed[["run_id", "experiment", "condition", "system", "trial",
                   "status", "error"]]


def check_against_logs(frame: pd.DataFrame, *, tolerance: float = 1e-6,
                       log_root: Path | None = None) -> list[dict]:
    """Re-derive every metric from raw ``events.csv`` and compare to the index.

    The index is a convenience; the logs are the evidence. This is what keeps
    the two from drifting apart — an edited log, a hand-patched index or a
    change to ``metrics.py`` made after the runs were recorded all show up here
    as a mismatch (CC-06, RP-07).
    """
    checked = ("completion_time_s", "goodput_bytes_per_s", "retransmission_count",
               "retransmission_overhead", "switch_count")
    mismatches = []
    for row in frame.to_dict("records"):
        directory = runner._resolve(row["log_dir"])
        if log_root is not None:
            directory = Path(log_root) / directory.name
        derived = metrics_mod.derive_from_run(directory)
        for column in checked:
            recorded, again = row[column], derived[column]
            if recorded is None or again is None:
                continue
            if abs(float(recorded) - float(again)) > tolerance * max(1.0, abs(float(again))):
                mismatches.append({"run_id": row["run_id"], "metric": column,
                                   "index": recorded, "from_logs": again})
    return mismatches


